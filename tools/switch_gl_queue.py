#!/usr/bin/env python3
"""Generate the Switch host's queued OpenGL ES entry points.

With the render thread (port/switch/host/host_render.c) the guest's OpenGL
imports are not Mesa's functions but functions that put the call in a queue,
which the thread that has the context takes them from. For each import of
the guest's (the list tools/android_gl_stubs.py writes) this writes, from
the function's prototype in the OpenGL ES headers, one of

- a queued call: the arguments are stored and the function returns. Every
  function that returns nothing and takes no pointer is one, and those
  whose pointer is an offset into a bound buffer;
- a queued call with a copy: the function reads memory of a size its other
  arguments tell (COPIES), which is stored with the call. A null pointer is
  stored as one; a size that is not known, or too large, makes it
- a call that waits: the render thread runs it with the caller's own
  arguments and the caller waits for it. Every function that returns
  something or writes through a pointer is one, and glFinish.

A few functions are written by hand in host_render.c (HAND); they get a
declaration here, and what is above to build on (the queued call as
a_<function>).

Usage: switch_gl_queue.py gl32.h gl2ext.h gl_imports.list output.inc
"""

import sys

from android_gl_stubs import prototypes, split_parameter

# pointers that are offsets into the buffer bound at the time
OFFSETS = {"glVertexAttribPointer", "glVertexAttribIPointer", "glDrawElements", "glDrawElementsBaseVertex"}

# function: (index of the pointer, the bytes it points at); the helpers are
# host_render.c's
COPIES = {
    "glUniform4fv": (2, "copy_count(a1, 16)"),
    "glUniform1iv": (2, "copy_count(a1, 4)"),
    "glVertexAttrib4fv": (1, "16"),
    "glDeleteTextures": (1, "copy_count(a0, 4)"),
    "glDeleteBuffers": (1, "copy_count(a0, 4)"),
    "glDeleteFramebuffers": (1, "copy_count(a0, 4)"),
    "glDeleteRenderbuffers": (1, "copy_count(a0, 4)"),
    "glDrawBuffers": (1, "copy_count(a0, 4)"),
    "glInvalidateFramebuffer": (2, "copy_count(a1, 4)"),
    "glBufferData": (2, "copy_count(a1, 1)"),
    "glBufferSubData": (3, "copy_count(a2, 1)"),
    "glCompressedTexImage2D": (7, "copy_count(a6, 1)"),
    "glCompressedTexImage3D": (8, "copy_count(a7, 1)"),
    "glTexImage2D": (8, "copy_pixels(a3, a4, 1, a6, a7)"),
    "glTexImage3D": (9, "copy_pixels(a3, a4, a5, a7, a8)"),
    "glTexSubImage2D": (8, "copy_pixels(a4, a5, 1, a6, a7)"),
}

# written in host_render.c
HAND = {"glGenTextures", "glPixelStorei"}

# what the caller means to wait for
WAITS = {"glFinish"}


def main():
    gl32, gl2ext, imports, output = sys.argv[1:5]
    protos = prototypes(gl32, gl2ext)
    names = [line.strip()[len("hostgl_"):] for line in open(imports, encoding="utf-8") if line.strip()]
    functions = []
    for name in names:
        if name not in protos:
            raise SystemExit(f"{name}: no prototype in the GLES headers")
        ret, params = protos[name]
        plist = [] if params in ("void", "") else [split_parameter(p)[0] for p in params.split(",")]
        functions.append((name, ret, plist))

    out = [
        "/* generated by tools/switch_gl_queue.py from the OpenGL ES headers and the guest's imports; do not edit */",
        "",
        "/* Mesa's functions */",
        "static struct",
        "{",
    ]
    for name, ret, plist in functions:
        out.append(f"\t{ret} (*{name})({', '.join(plist) or 'void'});")
    out += ["} real;", ""]

    table = []
    for name, ret, plist in functions:
        arguments = [f"a{index}" for index in range(len(plist))]
        declared = ", ".join(f"{ptype} {argument}" for ptype, argument in zip(plist, arguments)) or "void"
        passed = ", ".join(arguments)
        returns = ret != "void"
        pointers = [index for index, ptype in enumerate(plist) if "*" in ptype]
        queued = not returns and (not pointers or name in OFFSETS) and name not in WAITS
        copied = name in COPIES
        if copied and (returns or pointers != [COPIES[name][0]]):
            raise SystemExit(f"{name}: not the one pointer its copy is of")

        if not queued:
            # the call that waits
            members = [f"{ptype} {argument};" for ptype, argument in zip(plist, arguments)]
            if returns:
                members.append(f"{ret} result;")
            if members:
                out.append(f"struct s_{name} {{ {' '.join(members)} }};")
            out.append(f"static void y_{name}(void *context)")
            out.append("{")
            if members:
                out.append(f"\tstruct s_{name} *s = context;")
                out.append("")
            else:
                out.append("\t(void)context;")
            call = f"real.{name}({', '.join('s->' + argument for argument in arguments)})"
            out.append(f"\t{'s->result = ' if returns else ''}{call};")
            out.append("}")
            out.append(f"static {ret} s_{name}({declared})")
            out.append("{")
            if members:
                out.append(f"\tstruct s_{name} s;")
                out.append("")
                for argument in arguments:
                    out.append(f"\ts.{argument} = {argument};")
                out.append(f"\trender_call(y_{name}, &s);")
            else:
                out.append(f"\trender_call(y_{name}, NULL);")
            if returns:
                out.append("\treturn s.result;")
            out.append("}")

        if queued or copied:
            members = [f"{ptype} {argument};" for ptype, argument in zip(plist, arguments)]
            out.append(f"struct r_{name} {{ struct render_command command; {' '.join(members)} }};")
            out.append(f"static void x_{name}(const struct render_command *command)")
            out.append("{")
            if arguments:
                out.append(f"\tconst struct r_{name} *r = (const struct r_{name} *)command;")
                out.append("")
            else:
                out.append("\t(void)command;")
            out.append(f"\treal.{name}({', '.join('r->' + argument for argument in arguments)});")
            out.append("}")
            # (one written by hand calls this itself)
            out.append(f"static void {'a' if name in HAND else 'q'}_{name}({declared})")
            out.append("{")
            out.append(f"\tstruct r_{name} *r;")
            if copied:
                pointer, size = COPIES[name]
                out.append(f"\tsize_t size = a{pointer} ? {size} : 0;")
                out.append("")
                out.append("\tif (size > RENDER_COPY_MAXIMUM)")
                out.append("\t{")
                out.append(f"\t\ts_{name}({passed});")
                out.append("\t\treturn;")
                out.append("\t}")
                out.append(f"\tr = render_begin(sizeof(*r) + size, x_{name});")
            else:
                pointer = None
                out.append("")
                out.append(f"\tr = render_begin(sizeof(*r), x_{name});")
            for index, argument in enumerate(arguments):
                if index == pointer:
                    out.append(f"\tr->{argument} = {argument} ? memcpy(r + 1, {argument}, size) : NULL;")
                else:
                    out.append(f"\tr->{argument} = {argument};")
            if not arguments:
                out.append("\t(void)r;")
            out.append("\trender_end();")
            out.append("}")
        if name in HAND:
            out.append(f"static {ret} q_{name}({declared});")
        entry = f"q_{name}" if queued or copied or name in HAND else f"s_{name}"
        out.append("")
        table.append((name, entry))

    out.append("static const struct { const char *name; void *queued; void *real; } render_functions[] =")
    out.append("{")
    for name, entry in table:
        out.append(f'\t{{ "{name}", (void *){entry}, &real.{name} }},')
    out.append("};")
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
