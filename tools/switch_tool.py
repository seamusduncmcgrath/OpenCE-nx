#!/usr/bin/env python3
"""The Switch build's steps that need more than one program
(tools/switch_build.py's rules call it).

ninja starts each command without a shell on Windows, where devkitPro is
most often installed, so the steps the Android build writes as shell
pipelines (tools/android_build.py) are subcommands here instead:

    switch_tool.py guest-cc CC OUT SOURCE -- FLAGS...
        compiles a guest unit: C to arm64_32 assembly, that to ELF assembly
        (tools/android_asm_convert.py), and assembles it
    switch_tool.py guest-as CC OUT SOURCE
        assembles ELF assembly for the guest
    switch_tool.py musl-headers MUSL_DIR ARCH_DIR VERSION INCLUDE_DIR INTERNAL_DIR
        generates musl's bits/alltypes.h, bits/syscall.h and version.h
    switch_tool.py syscall-numbers SYSCALL_H_IN OUT
        the guest's system call numbers, as a header for the host
    switch_tool.py copy SOURCE DESTINATION
    switch_tool.py run [NAME=VALUE...] -- COMMAND...
        runs a command with environment variables set
"""

import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import android_asm_convert  # noqa: E402

GUEST_ASSEMBLER_TARGET = "--target=aarch64-none-elf"


def run(command) -> None:
    result = subprocess.run([str(part) for part in command], check=False)
    if result.returncode:
        sys.exit(result.returncode)


def guest_cc(arguments) -> None:
    cc, out, source = arguments[:3]
    flags = arguments[4:] if len(arguments) > 3 and arguments[3] == "--" else arguments[3:]
    darwin = out + ".darwin.s"
    converted = out + ".s"
    run([cc, "-MMD", "-MF", out + ".d", "-MT", out, *flags, "-S", source, "-o", darwin])
    with open(darwin, "r", encoding="utf-8", errors="surrogateescape") as f:
        lines = f.read().split("\n")
    try:
        text = android_asm_convert.Converter(lines).run()
    except android_asm_convert.ConvertError as error:
        print(f"{darwin}: {error}", file=sys.stderr)
        sys.exit(1)
    with open(converted, "w", encoding="utf-8", errors="surrogateescape", newline="\n") as f:
        f.write(text)
    run([cc, GUEST_ASSEMBLER_TARGET, "-c", converted, "-o", out])


def guest_as(arguments) -> None:
    cc, out, source = arguments[:3]
    run([cc, GUEST_ASSEMBLER_TARGET, "-c", source, "-o", out])


# musl's tools/mkalltypes.sed
ALLTYPES = (
    (re.compile(r"^TYPEDEF (.*) ([^ ]*);$"), "__NEED_{1}", "__DEFINED_{1}", "typedef {0} {1};"),
    (re.compile(r"^STRUCT +([^ ]*) (.*);$"), "__NEED_struct_{0}", "__DEFINED_struct_{0}", "struct {0} {1};"),
    (re.compile(r"^UNION +([^ ]*) (.*);$"), "__NEED_union_{0}", "__DEFINED_union_{0}", "union {0} {1};"),
)


def alltypes(paths) -> str:
    out = []
    for path in paths:
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            for pattern, need, defined, declaration in ALLTYPES:
                match = pattern.match(line)
                if match:
                    groups = match.groups()
                    out += [f"#if defined({need.format(*groups)}) && !defined({defined.format(*groups)})",
                            declaration.format(*groups), f"#define {defined.format(*groups)}", "#endif", ""]
                    break
            else:
                out.append(line)
    return "\n".join(out) + "\n"


def write_if_changed(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def syscall_names(syscall_in: Path) -> str:
    """the header's __NR_ lines again as SYS_ ones (musl's Makefile)"""
    lines = syscall_in.read_text(encoding="utf-8").splitlines()
    return "\n".join(line.replace("__NR_", "SYS_") for line in lines if "__NR_" in line) + "\n"


def musl_headers(arguments) -> None:
    musl, arch, version, include, internal = (Path(argument) if index != 2 else argument
                                              for index, argument in enumerate(arguments[:5]))
    write_if_changed(include / "bits" / "alltypes.h",
                     alltypes([arch / "bits" / "alltypes.h.in", musl / "include" / "alltypes.h.in"]))
    syscall_in = arch / "bits" / "syscall.h.in"
    write_if_changed(include / "bits" / "syscall.h",
                     syscall_in.read_text(encoding="utf-8").replace("\r\n", "\n") + syscall_names(syscall_in))
    write_if_changed(internal / "version.h", f'#define VERSION "{version}"\n')


def syscall_numbers(arguments) -> None:
    syscall_in, out = Path(arguments[0]), Path(arguments[1])
    # (as GUEST_SYS_ names: the host's own C library has a <sys/syscall.h>)
    text = "/* generated by tools/switch_tool.py from the guest's bits/syscall.h.in; do not edit */\n"
    text += syscall_names(syscall_in).replace("SYS_", "GUEST_SYS_")
    write_if_changed(out, text)


def copy(arguments) -> None:
    source, destination = Path(arguments[0]), Path(arguments[1])
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)


def run_with_environment(arguments) -> None:
    split = arguments.index("--")
    environment = dict(os.environ)
    for assignment in arguments[:split]:
        name, _, value = assignment.partition("=")
        environment[name] = value
    result = subprocess.run(arguments[split + 1:], env=environment, check=False)
    sys.exit(result.returncode)


COMMANDS = {
    "guest-cc": guest_cc,
    "guest-as": guest_as,
    "musl-headers": musl_headers,
    "syscall-numbers": syscall_numbers,
    "copy": copy,
    "run": run_with_environment,
}


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in COMMANDS:
        print(__doc__)
        sys.exit(2)
    COMMANDS[sys.argv[1]](sys.argv[2:])


if __name__ == "__main__":
    main()
